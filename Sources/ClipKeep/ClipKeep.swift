import AppKit
import SwiftUI

// Same polling idea as Paste: watch changeCount, read only when it moves.
final class ClipboardMonitor: ObservableObject {
    @Published private(set) var clips: [Clip]
    private let store: FileStore
    private let pasteboard = NSPasteboard.general
    private var lastChange: Int
    private var timer: Timer?

    // nspasteboard.org markers: password managers and transient writers ask not to be recorded.
    private static let skipTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ]

    init(store: FileStore = .standard) {
        self.store = store
        clips = store.load()
        lastChange = pasteboard.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
        timer?.tolerance = 0.2
    }

    private func poll() {
        guard pasteboard.changeCount != lastChange else { return }
        lastChange = pasteboard.changeCount
        let types = Set(pasteboard.types?.map(\.rawValue) ?? [])
        guard types.isDisjoint(with: Self.skipTypes),
              let text = pasteboard.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
        else { return }
        let app = NSWorkspace.shared.frontmostApplication?.localizedName
        clips = History.adding(Clip(text: text, app: app), to: clips)
        store.save(clips)
    }

    func copy(_ clip: Clip) {
        pasteboard.clearContents()
        pasteboard.setString(clip.text, forType: .string)
        lastChange = pasteboard.changeCount // don't re-capture our own write
        clips = History.adding(Clip(text: clip.text, app: clip.app), to: clips)
        store.save(clips)
    }

    func clear() {
        clips = []
        store.save(clips)
    }
}

struct HistoryView: View {
    @ObservedObject var monitor: ClipboardMonitor
    var onPick: () -> Void = {}
    @State private var query = ""

    var body: some View {
        VStack(alignment: .leading, spacing: 8) {
            TextField("Search", text: $query)
                .textFieldStyle(.roundedBorder)
            let results = History.search(query, in: monitor.clips)
            List(results) { clip in
                Button { monitor.copy(clip); onPick() } label: {
                    VStack(alignment: .leading, spacing: 2) {
                        Text(clip.text).lineLimit(2)
                        Text("\(clip.app ?? "Unknown") · \(clip.date.formatted(.relative(presentation: .named)))")
                            .font(.caption).foregroundStyle(.secondary)
                    }
                }
                .buttonStyle(.plain)
            }
            .overlay { if results.isEmpty { Text("No clips").foregroundStyle(.secondary) } }
            HStack {
                Text("\(monitor.clips.count) clips").font(.caption).foregroundStyle(.secondary)
                Spacer()
                Button("Clear") { monitor.clear() }
                Button("Quit") { NSApp.terminate(nil) }
            }
        }
        .padding(10)
        .frame(width: 360, height: 460)
    }
}

// Status item + popover instead of MenuBarExtra: MenuBarExtra has no API to open it from code, the hotkey needs one.
final class AppDelegate: NSObject, NSApplicationDelegate {
    private let monitor = ClipboardMonitor()
    private let statusItem = NSStatusBar.system.statusItem(withLength: NSStatusItem.squareLength)
    private let popover = NSPopover()
    private var hotKey: HotKey?

    func applicationDidFinishLaunching(_ notification: Notification) {
        statusItem.button?.image = NSImage(systemSymbolName: "doc.on.clipboard", accessibilityDescription: "ClipKeep")
        statusItem.button?.action = #selector(toggle)
        statusItem.button?.target = self
        popover.behavior = .transient
        popover.contentViewController = NSHostingController(
            rootView: HistoryView(monitor: monitor) { [weak self] in self?.popover.performClose(nil) })
        hotKey = HotKey(.default) { [weak self] in self?.toggle() }
    }

    @objc private func toggle() {
        if popover.isShown { popover.performClose(nil); return }
        guard let button = statusItem.button else { return }
        NSApp.activate(ignoringOtherApps: true) // accessory app: needed so the search field gets keyboard focus
        popover.show(relativeTo: button.bounds, of: button, preferredEdge: .minY)
    }
}

@main
enum ClipKeepMain {
    static func main() {
        if CommandLine.arguments.contains("--selftest") { SelfTest.run(); return }
        let app = NSApplication.shared
        let delegate = AppDelegate()
        app.delegate = delegate
        app.setActivationPolicy(.accessory) // menu bar only, no Dock icon
        app.run()
    }
}

enum SelfTest {
    static func run() {
        var h: [Clip] = []
        h = History.adding(Clip(text: "hello world", app: "Notes"), to: h)
        h = History.adding(Clip(text: "second", app: "Safari"), to: h)
        h = History.adding(Clip(text: "hello world", app: "Mail"), to: h)
        precondition(h.map(\.text) == ["hello world", "second"], "dedupe moves to top")
        precondition(History.search("WORLD hel", in: h).count == 1, "multi-word, case-insensitive")
        precondition(History.search("safari", in: h).first?.text == "second", "matches app name")
        precondition(History.search("", in: h).count == 2, "empty query returns all")
        for i in 0..<600 { h = History.adding(Clip(text: "\(i)"), to: h) }
        precondition(h.count == History.limit, "capped")

        let url = FileManager.default.temporaryDirectory.appendingPathComponent("clipkeep-test.json")
        let store = FileStore(url: url)
        store.save(h)
        precondition(store.load() == h, "file round-trip")
        try? FileManager.default.removeItem(at: url)
        print("selftest ok")
    }
}
